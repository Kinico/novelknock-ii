#!/usr/bin/env bash
# In-game performance overlay (MangoHud) for the Super+S "Performance" widget and Super+F12.
#   perf-hud.sh toggle | show | hide        show or hide the overlay in running games (no restart)
#   perf-hud.sh set <item> true|false       choose what it shows (fps, graph, gpu, gputemp, vram, clocks, cpu, cputemp, ram, power)
#   perf-hud.sh position <top-left|top-right|bottom-left|bottom-right>
#   perf-hud.sh status                      JSON: installed, loaded at login, shown, items, position
#   perf-hud.sh stats                       JSON: live GPU and CPU sensor readings for the widget
# MangoHud must be loaded into the game when it starts (MANGOHUD=1 at login does that for every
# Vulkan/Proton game). After that, showing and hiding works live: MangoHud re-reads its config file.
STATE="$HOME/.config/novelknock/hud.json"
CONF="$HOME/.config/MangoHud/MangoHud.conf"
mkdir -p "$(dirname "$STATE")" "$(dirname "$CONF")"

gpu_dir() {
    for d in /sys/class/drm/card*/device; do
        [ -f "$d/gpu_busy_percent" ] && { echo "$d"; return; }
    done
}

write_conf() {
    python3 - "$STATE" "$CONF" "${XDG_STATE_HOME:-$HOME/.local/state}/quickshell/user/generated/colors.json" <<'PYEOF'
import json, os, re, sys
state_p, conf_p, colors_p = sys.argv[1:4]
defaults = {"shown": False, "position": "top-left",
            "items": {"fps": True, "graph": True, "gpu": True, "gputemp": True, "vram": True, "clocks": False,
                      "cpu": True, "cputemp": True, "ram": True, "power": False}}
try:
    st = json.load(open(state_p))
except Exception:
    st = {}
items = dict(defaults["items"]); items.update(st.get("items", {}))
st = {**defaults, **st, "items": items}
json.dump(st, open(state_p, "w"), indent=2)

# keep the FPS limit set by ii's "MangoHud FPS" widget, and back up a config that wasn't ours
keep = []
if os.path.exists(conf_p):
    old = open(conf_p).read()
    if "Generated by perf-hud.sh" not in old and not os.path.exists(conf_p + ".bak"):
        open(conf_p + ".bak", "w").write(old)
    keep = [l for l in old.splitlines() if re.match(r"^\s*fps_limit\s*=", l)]

accent = "B4A0FF"
try:
    c = json.load(open(colors_p))
    accent = (c.get("primary") or c.get("colPrimary") or accent).lstrip("#")[:6]
except Exception:
    pass

lines = [
    "# Generated by perf-hud.sh (NovelKnock). Change it from Super+S > Performance, toggle with Super+F12.",
    "legacy_layout=false",
    f"position={st['position']}",
    "round_corners=12",
    "background_alpha=0.45",
    "background_color=101014",
    "font_size=18",
    "text_color=ECECEC",
    f"gpu_color={accent}", f"cpu_color={accent}", f"vram_color={accent}", f"ram_color={accent}",
    f"engine_color={accent}", f"frametime_color={accent}",
    "toggle_hud=Shift_R+F12",
    "blacklist=zen,zen-bin,firefox,chrome,chromium,brave,mpv,vlc,obs,discord,vesktop,electron,qs,quickshell",
]
m = st["items"]
if m["fps"]: lines += ["fps", "frametime"]
if m["graph"]: lines.append("frame_timing")
if m["gpu"]: lines.append("gpu_stats")
if m["gputemp"]: lines += ["gpu_temp", "gpu_junction_temp"]
if m["clocks"]: lines += ["gpu_core_clock", "gpu_mem_clock"]
if m["power"]: lines.append("gpu_power")
if m["vram"]: lines.append("vram")
if m["cpu"]: lines.append("cpu_stats")
if m["cputemp"]: lines.append("cpu_temp")
if m["ram"]: lines.append("ram")
lines += keep
if not st["shown"]:
    lines.append("no_display")
tmp = conf_p + ".tmp"
open(tmp, "w").write("\n".join(lines) + "\n")
os.replace(tmp, conf_p)            # MangoHud notices the change and reloads it in running games
PYEOF
}

set_state() {   # set_state <python expression on st>
    python3 - "$STATE" "$1" <<'PYEOF'
import json, sys
p, expr = sys.argv[1], sys.argv[2]
try:
    st = json.load(open(p))
except Exception:
    st = {}
st.setdefault("items", {})
exec(expr)
json.dump(st, open(p, "w"), indent=2)
PYEOF
}

case "$1" in
    toggle) set_state 'st["shown"] = not st.get("shown", False)'; write_conf ;;
    show)   set_state 'st["shown"] = True'; write_conf ;;
    hide)   set_state 'st["shown"] = False'; write_conf ;;
    set)
        case "$2" in fps|graph|gpu|gputemp|vram|clocks|cpu|cputemp|ram|power) ;; *) exit 1 ;; esac
        [ "$3" = "true" ] && v=True || v=False
        set_state "st['items']['$2'] = $v"; write_conf ;;
    position)
        case "$2" in top-left|top-right|bottom-left|bottom-right) ;; *) exit 1 ;; esac
        set_state "st['position'] = '$2'"; write_conf ;;
    init)
        write_conf ;;
    status)
        [ -f "$STATE" ] || write_conf
        installed=false; command -v mangohud >/dev/null && installed=true
        loaded=false; [ "$MANGOHUD" = "1" ] && loaded=true
        python3 -c 'import json,sys; st=json.load(open(sys.argv[1])); st["installed"]=sys.argv[2]=="true"; st["loaded"]=sys.argv[3]=="true"; print(json.dumps(st))' "$STATE" "$installed" "$loaded"
        ;;
    stats)
        d=$(gpu_dir)
        rd() { cat "$1" 2>/dev/null || echo 0; }
        busy=0; vu=0; vt=0; te=0; tj=0; clk=0; fan=0; pw=0; ct=0
        if [ -n "$d" ]; then
            busy=$(rd "$d/gpu_busy_percent"); vu=$(rd "$d/mem_info_vram_used"); vt=$(rd "$d/mem_info_vram_total")
            h=$(ls -d "$d"/hwmon/hwmon* 2>/dev/null | head -1)
            if [ -n "$h" ]; then
                te=$(rd "$h/temp1_input"); tj=$(rd "$h/temp2_input"); clk=$(rd "$h/freq1_input"); fan=$(rd "$h/fan1_input")
                pw=$(cat "$h/power1_average" 2>/dev/null || cat "$h/power1_input" 2>/dev/null || echo 0)
            fi
        fi
        for h in /sys/class/hwmon/hwmon*; do
            n=$(cat "$h/name" 2>/dev/null)
            case "$n" in k10temp|zenpower|coretemp) ct=$(rd "$h/temp1_input"); break ;; esac
        done
        printf '{"gpu":%s,"vramUsed":%s,"vramTotal":%s,"gpuTemp":%s,"hotspot":%s,"clock":%s,"fan":%s,"power":%s,"cpuTemp":%s}\n' \
            "${busy:-0}" "${vu:-0}" "${vt:-0}" "$(( ${te:-0} / 1000 ))" "$(( ${tj:-0} / 1000 ))" "$(( ${clk:-0} / 1000000 ))" "${fan:-0}" "$(( ${pw:-0} / 1000000 ))" "$(( ${ct:-0} / 1000 ))"
        ;;
    *)
        echo "usage: $0 toggle | show | hide | set <item> true|false | position <corner> | status | stats" >&2
        exit 1 ;;
esac
